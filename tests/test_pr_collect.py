"""Mocked-response tests for pr_collect.py. See test_github_client.py's
module docstring for why these are mocked rather than live."""

from unittest.mock import MagicMock

from afp.github_client import GitHubClient
from afp.pr_collect import build_pr_record


def test_build_pr_record_rubber_stamp_flag():
    client = GitHubClient(token="fake-token")
    client.get_pull_request = MagicMock(return_value={
        "number": 1,
        "title": "Fix typo",
        "body": "",
        "head": {"ref": "fix-typo"},
        "labels": [],
        "user": {"login": "janedoe"},
        "created_at": "2026-03-01T10:00:00Z",
        "merged_at": "2026-03-01T10:10:00Z",
        "merge_commit_sha": "abc123",
        "additions": 2,
        "deletions": 1,
        "changed_files": 1,
    })
    client.list_pr_reviews = MagicMock(return_value=[
        {"submitted_at": "2026-03-01T10:05:00Z", "state": "APPROVED",
         "user": {"login": "reviewer"}},  # approved 5 min after creation
    ])
    client.list_pr_review_comments = MagicMock(return_value=[])  # zero comments

    record = build_pr_record(client, "o", "r", 1)
    assert record.pr_size == 3
    assert record.review_comment_count == 0
    assert record.review_latency_seconds == 300.0
    assert record.approval_latency_seconds == 300.0
    assert record.rubber_stamp_flag is True  # 0 comments + approved 5 min < 15 min threshold


def test_build_pr_record_not_rubber_stamp_when_commented():
    client = GitHubClient(token="fake-token")
    client.get_pull_request = MagicMock(return_value={
        "number": 2,
        "title": "Add feature",
        "body": "",
        "head": {"ref": "feature-x"},
        "labels": [],
        "user": {"login": "janedoe"},
        "created_at": "2026-03-01T10:00:00Z",
        "merged_at": "2026-03-01T12:00:00Z",
        "merge_commit_sha": "def456",
        "additions": 50,
        "deletions": 10,
        "changed_files": 3,
    })
    client.list_pr_reviews = MagicMock(return_value=[{"submitted_at": "2026-03-01T10:10:00Z", "state": "APPROVED",
                                                        "user": {"login": "reviewer"}}])
    client.list_pr_review_comments = MagicMock(return_value=[{"id": 1}, {"id": 2}])

    record = build_pr_record(client, "o", "r", 2)
    assert record.review_comment_count == 2
    assert record.review_depth == 2 / 60
    assert record.rubber_stamp_flag is False


def test_build_pr_record_detects_pr_marker_label():
    client = GitHubClient(token="fake-token")
    client.get_pull_request = MagicMock(return_value={
        "number": 3,
        "title": "Automated change",
        "body": "Generated by Claude Code",
        "head": {"ref": "claude/auto-fix"},
        "labels": [{"name": "ai-generated"}],
        "user": {"login": "someuser"},
        "created_at": "2026-03-01T10:00:00Z",
        "merged_at": None,
        "merge_commit_sha": None,
        "additions": 10,
        "deletions": 0,
        "changed_files": 1,
    })
    client.list_pr_reviews = MagicMock(return_value=[])
    client.list_pr_review_comments = MagicMock(return_value=[])

    record = build_pr_record(client, "o", "r", 3)
    assert record.label.label == "agent_labeled"
    assert record.label.agent_brand == "claude_code"
    assert record.label.label_source == "pr_marker"
